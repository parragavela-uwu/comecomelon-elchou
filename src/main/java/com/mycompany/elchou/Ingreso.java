    /**
     * Carga y escala el ícono de pollito de forma portable en el JLabel (escalado a 50x50).
     */
    private void setLogoIcon() {
        Image img = null;
        // Intentar cargar desde el classpath
        java.net.URL imgUrl = Ingreso.class.getResource("/com/mycompany/elchou/pollito-icon.png");
        if (imgUrl != null) {
            img = new javax.swing.ImageIcon(imgUrl).getImage();
        } else {
            // Intentar cargar desde la raíz del proyecto
            java.io.File file = new java.io.File("pollito-icon.png");
            if (file.exists()) {
                img = new javax.swing.ImageIcon(file.getAbsolutePath()).getImage();
            } else {
                // Intentar cargar desde la ruta relativa de desarrollo
                file = new java.io.File("src/main/java/com/mycompany/elchou/pollito-icon.png");
                if (file.exists()) {
                    img = new javax.swing.ImageIcon(file.getAbsolutePath()).getImage();
                }
            }
        }
        
        if (img != null) {
            // Escalar a 50x50 para alinearlo de manera armónica al costado del título
            Image scaledImg = img.getScaledInstance(50, 50, Image.SCALE_SMOOTH);
            lblLogo.setIcon(new javax.swing.ImageIcon(scaledImg));
        }
    }

