    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String user = txtUsuario.getText().trim();
        String pass = new String(txtPassword.getPassword()).trim();

        if (user.isEmpty() || pass.isEmpty()) {
            lblGeneralMessage.setForeground(new java.awt.Color(220, 38, 38)); // Red-600
            lblGeneralMessage.setText("Completa todos los campos");
        } else if (user.equals("usuario") && pass.equals("12345")) {
            lblGeneralMessage.setForeground(new java.awt.Color(22, 163, 74)); // Green-600
            lblGeneralMessage.setText("Bienvenido");
            
            // Cerrar ventana de login e iniciar el segundo frame (RegistroPlatos)
            javax.swing.JFrame currentFrame = (javax.swing.JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
            if (currentFrame != null) {
                currentFrame.dispose();
            }
            
            javax.swing.SwingUtilities.invokeLater(() -> {
                RegistroPlatos frame2 = new RegistroPlatos();
                frame2.setVisible(true);
            });
        } else if (user.equals("oretarao") && pass.equals("12345")) {
            lblGeneralMessage.setForeground(new java.awt.Color(22, 163, 74)); // Green-600
            lblGeneralMessage.setText("Bienvenido");
            
            // Cerrar ventana de login e iniciar el tercer frame (ListaPlatos como no-admin)
            javax.swing.JFrame currentFrame = (javax.swing.JFrame) javax.swing.SwingUtilities.getWindowAncestor(this);
            if (currentFrame != null) {
                currentFrame.dispose();
            }
            
            javax.swing.SwingUtilities.invokeLater(() -> {
                ListaPlatos frame3 = new ListaPlatos(false);
                frame3.setVisible(true);
            });
        } else {
            lblGeneralMessage.setForeground(new java.awt.Color(220, 38, 38)); // Red-600
            lblGeneralMessage.setText("Algo está incorrecto.");
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

